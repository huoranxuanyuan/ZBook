"""Optional search rendering with the user's installed Edge or Chrome.

Uses an isolated application profile and standard headless flags. No browser,
driver or credentials is bundled or borrowed from a user profile.
"""
from pathlib import Path
from urllib.parse import urlencode
import hashlib
import logging
import os
import subprocess
import threading
import time
import cover_sources
from paths import ROOT,ARCHIVE
from cache_maintenance import create_maintenance,_lock,_unlock

LOG=logging.getLogger(__name__)
_LOCK=threading.Lock()


def find_browser():
    candidates=[]
    for variable in ('ProgramFiles(x86)','ProgramFiles','LOCALAPPDATA'):
        value=os.environ.get(variable)
        if value:
            base=Path(value)
            candidates.extend([base/'Microsoft/Edge/Application/msedge.exe',base/'Google/Chrome/Application/chrome.exe'])
    return next((path for path in candidates if path.is_file()),None)


def search_url(engine,title,author=''):
    if engine=='Google 图片':
        return 'https://www.google.com/search?'+urlencode({'q':f'"{title}" {author}'.strip(),'udm':2})
    if engine=='百度图片':
        return 'https://image.baidu.com/search/index?'+urlencode({'tn':'baiduimage','word':title})
    raise ValueError('不支持的图片来源')


def render(url):
    # Search URLs are generated by search_url; never accept arbitrary browser navigation.
    from urllib.parse import urlparse
    parsed=urlparse(url)
    if parsed.scheme!='https' or parsed.hostname not in ('www.google.com','image.baidu.com') or parsed.port not in (None,443) or parsed.username or parsed.password:
        raise ValueError('不支持的浏览器搜索地址')
    root=ARCHIVE/'browser-search'
    maintenance=create_maintenance(ROOT,kind='browser-search')
    try:
        maintenance.protect_resource(root)
        root.mkdir(parents=True,exist_ok=True)
        if not _LOCK.acquire(timeout=30):raise ValueError('其他书籍正在扩大搜索，请稍后重试')
        try:
            with (root/'.render.lock').open('a+b') as guard:
                if guard.tell()==0:guard.write(b'0');guard.flush()
                deadline=time.monotonic()+30
                while True:
                    try:_lock(guard);break
                    except OSError:
                        if time.monotonic()>deadline:raise ValueError('另一个窗口正在补充搜索，请稍后重试')
                        time.sleep(.1)
                try:return _render_locked(url,root)
                finally:_unlock(guard)
        finally:_LOCK.release()
    finally:maintenance.finish()


def _render_locked(url,root):
    browser=find_browser()
    if not browser:
        raise ValueError('未找到已安装的 Edge 或 Chrome，可在浏览器中继续查找')
    key=hashlib.sha256(url.encode('utf-8')).hexdigest()
    output=root/(key+'.html')
    errors=root/(key+'.log')
    if output.is_file() and output.stat().st_size<=10_000_000 and time.time()-output.stat().st_mtime<600:
        text=output.read_text(encoding='utf-8',errors='replace')
        if len(text)>200 and not any(x in text for x in ('captcha-form','百度安全验证','challenge-form')):
            return text
    try:
        profile=root/'profile'
        profile.mkdir(exist_ok=True)
        command=[str(browser),'--headless','--no-first-run','--no-default-browser-check',
                 '--disable-extensions','--disable-background-networking','--block-new-web-contents','--dump-dom','--timeout=12000','--virtual-time-budget=8000',
                 '--disk-cache-size=16777216','--user-data-dir='+str(profile),url]
        with output.open('wb') as target,errors.open('wb') as error:
            process=subprocess.Popen(command,stdout=target,stderr=error,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
            try:
                deadline=time.monotonic()+25
                while process.poll() is None:
                    if time.monotonic()>deadline or output.stat().st_size>10_000_000 or errors.stat().st_size>2_000_000:
                        raise subprocess.TimeoutExpired(command,25)
                    time.sleep(.1)
                result=process.returncode
            except subprocess.TimeoutExpired:
                # Only the process created above and its own children are closed.
                taskkill=Path(os.environ.get('SystemRoot','C:/Windows'))/'System32/taskkill.exe'
                subprocess.run([str(taskkill),'/pid',str(process.pid),'/t','/f'],stdout=error,stderr=error,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0),timeout=8)
                raise ValueError('补充搜索超时，可稍后重试')
        if result or output.stat().st_size>10_000_000:
            raise ValueError('浏览器未返回可用的图片搜索页面')
        text=output.read_text(encoding='utf-8',errors='replace')
        if 'id="main-frame-error"' in text or 'chrome-error://chromewebdata/' in text:raise ValueError('浏览器未能连接搜索站点，请检查当前网络或代理')
        if any(marker in text for marker in ('id="captcha-form"','unusual traffic from your computer','百度安全验证','id="challenge-form"','Your connection is not private')):
            raise ValueError('来源要求人工验证，请在浏览器中继续查找')
        return text
    finally:
        if (root/'profile').exists():os.utime(root/'profile',None)


def search_images(engine,title,author=''):
    url=search_url(engine,title,author)
    text=render(url)
    if engine=='Google 图片':
        return cover_sources.parse_google_images(text,url)
    parser=cover_sources.ImageLinks('baidu',url)
    parser.feed(text)
    return parser.rows
